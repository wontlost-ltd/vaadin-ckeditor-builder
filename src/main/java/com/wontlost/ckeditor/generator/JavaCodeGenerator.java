package com.wontlost.ckeditor.generator;

import com.wontlost.ckeditor.CKEditorPlugin;
import com.wontlost.ckeditor.VaadinCKEditor;
import com.wontlost.ckeditor.domain.BuilderState;
import com.wontlost.ckeditor.domain.PluginCatalogue;
import com.wontlost.ckeditor.domain.BuilderState.CodeBlockLanguageConfig;
import com.wontlost.ckeditor.domain.BuilderState.CustomPluginConfig;
import com.wontlost.ckeditor.domain.BuilderState.MentionFeedConfig;
import com.wontlost.ckeditor.domain.BuilderState.ToolbarStyleConfig;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Java Code Generator
 * Generates Vaadin CKEditor Java configuration code
 */
public class JavaCodeGenerator implements CodeGenerator {

    private static final DateTimeFormatter TIMESTAMP_FORMAT =
        DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    @Override
    public String generate(BuilderState state) {
        StringBuilder sb = new StringBuilder();
        String timestamp = LocalDateTime.now().format(TIMESTAMP_FORMAT);

        // File header comment
        sb.append("// VaadinCKEditor Configuration\n");
        sb.append("// Generated by CKEditor Builder at ").append(timestamp).append("\n");
        sb.append("// https://github.com/wontlost-ltd/vaadin-ckeditor\n");
        sb.append("// Open Source + Commercial Support\n");
        sb.append("// Target: com.wontlost:ckeditor-vaadin:").append(VaadinCKEditor.getVersion()).append("\n");
        sb.append("//\n");
        sb.append("// Toolbar Display Mode:\n");
        sb.append("// - Multi-line (default): config.setToolbar(items, true)  - All buttons visible\n");
        sb.append("// - Single-line: config.setToolbar(items, false) - Overflow goes to menu\n\n");

        // Import statements
        generateImports(sb, state);

        // Generate CKEditorConfig (if advanced config exists)
        if (hasAdvancedConfig(state)) {
            generateConfigCode(sb, state);
            sb.append("\n");
        }

        // Create editor using Builder API
        generateBuilderCode(sb, state);

        // Add to layout example
        sb.append("\n// Add to layout\n");
        sb.append("add(editor);\n");

        // Event listener examples
        generateEventListenerCode(sb, state);

        // Custom CSS example (if any)
        if (state.getCustomCss() != null && !state.getCustomCss().isEmpty()) {
            sb.append("\n");
            generateCustomCssCode(sb, state);
        }

        return sb.toString();
    }

    private void generateImports(StringBuilder sb, BuilderState state) {
        // com.wontlost.ckeditor.* 覆盖 CKEditorConfig、CustomPlugin、HtmlSupport、FullscreenPage、CodeHighlightTheme 等
        sb.append("import com.wontlost.ckeditor.*;\n");

        if (state.getDependencyMode() != BuilderState.DependencyMode.AUTO_RESOLVE) {
            sb.append("import com.wontlost.ckeditor.VaadinCKEditorBuilder.DependencyMode;\n");
        }

        sb.append("\n");
    }

    private boolean hasAdvancedConfig(BuilderState state) {
        return (state.getPlaceholder() != null && !state.getPlaceholder().isEmpty()) ||
               !state.getFontSizes().isEmpty() || state.isAllowAnyFontSize() ||
               !state.getFontFamilies().isEmpty() ||
               !state.getAlignmentOptions().isEmpty() ||
               hasCustomLinkConfig(state) ||
               !state.getSimpleUploadUrl().isEmpty() ||
               state.isAllowPrivateNetworks() ||
               !state.getImageToolbar().isEmpty() || !state.getImageStyles().isEmpty() ||
               !state.getTableContentToolbar().isEmpty() ||
               !state.getMentionFeeds().isEmpty() ||
               !state.getCodeBlockLanguages().isEmpty() ||
               state.isMediaEmbedPreviewsInData() ||
               !state.getEffectiveToolbarItems().isEmpty() ||
               (state.getToolbarStyle() != null && state.getToolbarStyle().hasAnyStyle()) ||
               state.isGhsEnabled() ||
               state.hasPlugin(CKEditorPlugin.CKBOX) ||
               hasAiAssistant(state);
    }

    private boolean hasCustomLinkConfig(BuilderState state) {
        return !"https://".equals(state.getLinkDefaultProtocol()) || !state.isAddTargetToExternalLinks();
    }

    private boolean hasAiAssistant(BuilderState state) {
        return state.getPremiumPlugins().stream()
            .anyMatch(p -> PluginCatalogue.AI_ASSISTANT.equals(p.getName()));
    }

    /**
     * CKEditorConfig 代码：只使用 addon 6.2 真实存在的 setter（链式返回 CKEditorConfig），
     * 没有类型化 setter 的配置项用 {@code set(dotted.path, value)} 写成嵌套对象。
     */
    private void generateConfigCode(StringBuilder sb, BuilderState state) {
        sb.append("// CKEditor Advanced Configuration\n");
        sb.append("CKEditorConfig config = new CKEditorConfig()");

        if (state.getPlaceholder() != null && !state.getPlaceholder().isEmpty()) {
            sb.append("\n    .setPlaceholder(").append(quote(state.getPlaceholder())).append(")");
        }

        if (!state.getFontSizes().isEmpty() || state.isAllowAnyFontSize()) {
            sb.append("\n    .setFontSize(");
            if (state.isAllowAnyFontSize()) {
                sb.append("true");
                if (!state.getFontSizes().isEmpty()) sb.append(", ");
            }
            sb.append(quoteAll(state.getFontSizes())).append(")");
        }

        if (!state.getFontFamilies().isEmpty()) {
            sb.append("\n    .setFontFamily(").append(quoteAll(state.getFontFamilies())).append(")");
        }

        if (!state.getAlignmentOptions().isEmpty()) {
            sb.append("\n    .setAlignment(").append(quoteAll(state.getAlignmentOptions())).append(")");
        }

        if (hasCustomLinkConfig(state)) {
            sb.append("\n    .setLink(").append(quote(state.getLinkDefaultProtocol())).append(", ")
              .append(state.isAddTargetToExternalLinks()).append(")");
        }

        if (!state.getSimpleUploadUrl().isEmpty()) {
            Map<String, String> headers = state.getSimpleUploadHeaders();
            sb.append("\n    .setSimpleUpload(").append(quote(state.getSimpleUploadUrl()));
            if (!headers.isEmpty() || state.isSimpleUploadWithCredentials()) {
                // Map.ofEntries 没有 Map.of 的 10 对上限
                sb.append(", java.util.Map.ofEntries(")
                  .append(headers.entrySet().stream()
                      .map(e -> "java.util.Map.entry(" + quote(e.getKey()) + ", " + quote(e.getValue()) + ")")
                      .collect(Collectors.joining(", ")))
                  .append("), ").append(state.isSimpleUploadWithCredentials());
            }
            sb.append(")");
        }

        if (state.isAllowPrivateNetworks()) {
            sb.append("\n    .allowPrivateNetworks(true)");
        }

        if (!state.getImageToolbar().isEmpty() || !state.getImageStyles().isEmpty()) {
            sb.append("\n    .setImage(").append(stringArray(state.getImageToolbar())).append(", ")
              .append(stringArray(state.getImageStyles())).append(")");
        }

        if (!state.getTableContentToolbar().isEmpty()) {
            sb.append("\n    .setTable(").append(stringArray(state.getTableContentToolbar())).append(")");
        }

        // shouldNotGroupWhenFull = true：多行全部显示；false：单行，溢出项进入 ⋮ 菜单
        List<String> toolbar = state.getEffectiveToolbarItems();
        if (!toolbar.isEmpty()) {
            sb.append("\n    // Toolbar config: 2nd param true=multi-line, false=single-line (overflow to menu)\n");
            sb.append("    .setToolbar(").append(stringArray(toolbar)).append(", true)");
        }

        if (!state.getCodeBlockLanguages().isEmpty()) {
            sb.append("\n    .setCodeBlock(").append(quote(state.getCodeBlockIndent()));
            for (CodeBlockLanguageConfig lang : state.getCodeBlockLanguages()) {
                sb.append(",\n        CKEditorConfig.CodeBlockLanguage.of(")
                  .append(quote(lang.getLanguage())).append(", ").append(quote(lang.getLabel())).append(")");
            }
            sb.append(")");
        }

        if (!state.getMentionFeeds().isEmpty()) {
            sb.append("\n    .setMention(");
            for (int i = 0; i < state.getMentionFeeds().size(); i++) {
                MentionFeedConfig feed = state.getMentionFeeds().get(i);
                if (i > 0) sb.append(",");
                sb.append("\n        new CKEditorConfig.MentionFeed(").append(quote(feed.getMarker())).append(", ")
                  .append(stringArray(feed.getFeed())).append(", ").append(feed.getMinimumCharacters()).append(")");
            }
            sb.append(")");
        }

        if (state.isMediaEmbedPreviewsInData()) {
            sb.append("\n    .setMediaEmbed(true)");
        }

        // General HTML Support（addon 6.2 HtmlSupport：默认禁止 <script>、<iframe> 与 on* 属性）
        if (state.isGhsEnabled()) {
            List<String> elements = state.getHtmlSupportAllowedElements();
            if (elements.isEmpty()) {
                sb.append("\n    // All elements, attributes, classes and styles except <script>, <iframe> and on* attributes");
                sb.append("\n    .setHtmlSupport(HtmlSupport.allowAll())");
            } else {
                sb.append("\n    .setHtmlSupport(HtmlSupport.create()")
                  .append("\n        .allow(HtmlSupport.Rule.elements(").append(quoteAll(elements))
                  .append(").attributes(true).classes(true).styles(true)))");
            }
        }

        // CKBox：premium feature，需要付费 CKBox 服务；令牌端点用点号路径写成 ckbox.tokenUrl
        if (state.hasPlugin(CKEditorPlugin.CKBOX)) {
            sb.append("\n    // CKBox is a paid CKEditor service: point this at your CKBox token endpoint")
              .append("\n    .set(\"ckbox.tokenUrl\", \"https://your-server.example.com/ckbox/token\")");
        }

        // AIAssistant（legacy）需要文本适配器：OpenAITextAdapter 指向你自己的代理
        if (hasAiAssistant(state)) {
            sb.append("\n    // AI Assistant needs a text adapter: point OpenAITextAdapter at your own proxy endpoint")
              .append("\n    .set(\"ai.assistant.adapter.openAI.apiUrl\", \"https://your-server.example.com/api/ai/openai\")");
        }

        ToolbarStyleConfig toolbarStyle = state.getToolbarStyle();
        if (toolbarStyle != null && toolbarStyle.hasAnyStyle()) {
            sb.append("\n    .setToolbarStyle(CKEditorConfig.ToolbarStyle.builder()");
            appendStyle(sb, "background", toolbarStyle.getBackground());
            appendStyle(sb, "borderColor", toolbarStyle.getBorderColor());
            appendStyle(sb, "borderRadius", toolbarStyle.getBorderRadius());
            appendStyle(sb, "buttonBackground", toolbarStyle.getButtonBackground());
            appendStyle(sb, "buttonHoverBackground", toolbarStyle.getButtonHoverBackground());
            appendStyle(sb, "buttonActiveBackground", toolbarStyle.getButtonActiveBackground());
            appendStyle(sb, "buttonOnBackground", toolbarStyle.getButtonOnBackground());
            appendStyle(sb, "buttonOnColor", toolbarStyle.getButtonOnColor());
            appendStyle(sb, "iconColor", toolbarStyle.getIconColor());
            sb.append("\n        .build())");
        }

        sb.append(";\n");
    }

    private void appendStyle(StringBuilder sb, String method, String value) {
        if (value != null) {
            sb.append("\n        .").append(method).append("(").append(quote(value)).append(")");
        }
    }

    private void generateBuilderCode(StringBuilder sb, BuilderState state) {
        sb.append("// Create editor using Builder API\n");
        sb.append("VaadinCKEditor editor = VaadinCKEditor.create()\n");
        sb.append("    .withPreset(CKEditorPreset.").append(state.getPreset().name()).append(")\n");
        sb.append("    .withType(CKEditorType.").append(state.getEditorType().name()).append(")\n");
        sb.append("    .withTheme(CKEditorTheme.").append(state.getTheme().name()).append(")\n");
        sb.append("    .withLanguage(").append(quote(state.getLanguage())).append(")\n");
        sb.append("    .withWidth(").append(quote(state.getEditorWidth())).append(")\n");
        sb.append("    .withHeight(").append(quote(state.getEditorHeight())).append(")");

        if (state.hasLicenseKey()) {
            sb.append("\n    // Recommended: Get License Key from environment variable\n");
            sb.append("    .withLicenseKey(System.getenv(\"CKEDITOR_LICENSE_KEY\"))");
        }

        if (hasAdvancedConfig(state)) {
            sb.append("\n    .withConfig(config)");
        }

        if (state.getDependencyMode() != BuilderState.DependencyMode.AUTO_RESOLVE) {
            sb.append("\n    .withDependencyMode(DependencyMode.")
              .append(state.getDependencyMode().name()).append(")");
        }

        // 与实时预览使用同一套插件集：预设之外的选中项 addPlugin，预设中被取消的 removePlugin
        for (CKEditorPlugin plugin : state.getSelectedPlugins()) {
            if (!state.getPreset().hasPlugin(plugin)) {
                sb.append("\n    .addPlugin(CKEditorPlugin.").append(plugin.name()).append(")");
            }
        }
        for (CKEditorPlugin presetPlugin : state.getPreset().getPlugins()) {
            if (!state.hasPlugin(presetPlugin)) {
                sb.append("\n    .removePlugin(CKEditorPlugin.").append(presetPlugin.name()).append(")");
            }
        }

        // Premium Plugins：fromPremium 不带工具栏项，带工具栏项时用 builder(...).premium()
        for (CustomPluginConfig plugin : state.getPremiumPlugins()) {
            sb.append("\n    .addCustomPlugin(");
            if (plugin.getToolbarItems().isEmpty()) {
                sb.append("CustomPlugin.fromPremium(").append(quote(plugin.getName())).append("))");
            } else {
                sb.append("CustomPlugin.builder(").append(quote(plugin.getName())).append(").premium()")
                  .append("\n        .withToolbarItems(").append(quoteAll(plugin.getToolbarItems())).append(")")
                  .append("\n        .build())");
            }
        }
        if (hasAiAssistant(state) && state.getPremiumPlugins().stream()
                .noneMatch(p -> PluginCatalogue.OPENAI_TEXT_ADAPTER.equals(p.getName()))) {
            sb.append("\n    .addCustomPlugin(CustomPlugin.fromPremium(")
              .append(quote(PluginCatalogue.OPENAI_TEXT_ADAPTER)).append("))");
        }

        for (CustomPluginConfig plugin : state.getCustomPlugins()) {
            sb.append("\n    .addCustomPlugin(CustomPlugin.builder(").append(quote(plugin.getName())).append(")\n");
            sb.append("        .withImportPath(").append(quote(plugin.getImportPath())).append(")");
            if (!plugin.getToolbarItems().isEmpty()) {
                sb.append("\n        .withToolbarItems(").append(quoteAll(plugin.getToolbarItems())).append(")");
            }
            sb.append("\n        .build())");
        }

        generateAddon62Options(sb, state);

        if (state.isViewOnly()) {
            sb.append("\n    .withViewOnly()");
        } else {
            if (state.isReadOnly()) {
                sb.append("\n    .readOnly(true)");
            }
            if (state.isHideToolbar()) {
                sb.append("\n    .withHideToolbar(true)");
            }
        }

        if (state.isAutosaveEnabled()) {
            sb.append("\n    // Autosave: called with the editor content, debounced by ")
              .append(state.getAutosaveInterval()).append(" ms")
              .append("\n    .withAutosave(content -> {\n        // Save content to your database\n    }, ")
              .append(state.getAutosaveInterval()).append(")");
        }

        if (state.getInitialValue() != null && !state.getInitialValue().isEmpty()) {
            sb.append("\n    .withValue(").append(quote(state.getInitialValue())).append(")");
        }

        // 工具栏已在 config.setToolbar() 中配置（含 shouldNotGroupWhenFull），不再用 withToolbar() 覆盖
        sb.append("\n    .build();\n");

        generatePostBuildConfig(sb, state);
    }

    /** addon 6.2：全屏页面宽度、字数统计与上限、代码块高亮。只输出与默认值不同的项。 */
    private void generateAddon62Options(StringBuilder sb, BuilderState state) {
        if (state.hasCustomFullscreenPage()) {
            sb.append("\n    .withFullscreenPage(").append(fullscreenPageExpression(state)).append(")");
        }
        if (state.isWordCountVisible()) {
            sb.append("\n    .withWordCountVisible(true)");
        }
        if (state.getMaxWords() > 0) {
            sb.append("\n    .withMaxWords(").append(state.getMaxWords()).append(")");
        }
        if (state.getMaxCharacters() > 0) {
            sb.append("\n    .withMaxCharacters(").append(state.getMaxCharacters()).append(")");
        }
        if (state.usesCodeBlockHighlighting()) {
            sb.append("\n    .withCodeBlockHighlighting(CodeHighlightTheme.")
              .append(state.getCodeHighlightTheme().name()).append(")");
        }
    }

    private String fullscreenPageExpression(BuilderState state) {
        return switch (state.getFullscreenPageMode()) {
            case A4_FIT -> "FullscreenPage.A4_FIT";
            case A4 -> "FullscreenPage.A4";
            case FULL_WIDTH -> "FullscreenPage.FULL_WIDTH";
            case CUSTOM -> "FullscreenPage.custom(" + quote(state.getFullscreenCustomWidth()) + ")";
        };
    }

    private void generatePostBuildConfig(StringBuilder sb, BuilderState state) {
        if (state.isMinimapEnabled()) {
            sb.append("\n// Enable Minimap (Decoupled mode only)\n");
            sb.append("editor.setMinimapEnabled(true);\n");
        }
    }

    private void generateEventListenerCode(StringBuilder sb, BuilderState state) {
        sb.append("\n// Listen for content changes\n");
        sb.append("editor.addValueChangeListener(event -> {\n");
        sb.append("    String content = event.getValue();\n");
        sb.append("    // Handle content change\n");
        sb.append("});\n");

        if (state.usesWordCount()) {
            sb.append("\n// Live word / character count (reported at most every 500 ms)");
            if (state.getMaxWords() > 0 || state.getMaxCharacters() > 0) {
                sb.append("\n// Over the limit the field is invalid (HasValidator); input is not truncated");
            }
            sb.append("\neditor.addWordCountChangeListener(event -> {\n");
            sb.append("    int words = event.getWords();\n");
            sb.append("    int characters = event.getCharacters();\n");
            sb.append("});\n");
        }

        if (!state.getSimpleUploadUrl().isEmpty()) {
            sb.append("\n// Alternative to SimpleUpload: handle uploads on the server\n");
            sb.append("// editor.setUploadHandler((context, inputStream) ->\n");
            sb.append("//     uploadService.upload(context.getFileName(), inputStream)\n");
            sb.append("//         .thenApply(com.wontlost.ckeditor.handler.UploadHandler.UploadResult::new));\n");
            sb.append("// Max file size: ").append(state.getUploadMaxFileSize()).append(" bytes");
            if (!state.getUploadAllowedMimeTypes().isEmpty()) {
                sb.append(", allowed types: ").append(String.join(", ", state.getUploadAllowedMimeTypes()));
            }
            sb.append("\n");
        }
    }

    private void generateCustomCssCode(StringBuilder sb, BuilderState state) {
        sb.append("// ═══════════════════════════════════════════════════════════════════\n");
        sb.append("// Custom CSS Injection Guide\n");
        sb.append("// ═══════════════════════════════════════════════════════════════════\n");
        sb.append("// Method 1: JavaScript dynamic injection (recommended for runtime styles)\n");
        sb.append("//   Pros: Flexible, can be modified dynamically\n");
        sb.append("//   Cons: Requires waiting for editor initialization\n");
        sb.append("//\n");
        sb.append("// Method 2: CSS file import (recommended for static styles)\n");
        sb.append("//   1. Save CSS to frontend/themes/your-theme/styles.css\n");
        sb.append("//   2. Vaadin project will auto-load theme styles\n");
        sb.append("//\n");
        sb.append("// Method 3: @CssImport annotation\n");
        sb.append("//   @CssImport(\"./styles/ckeditor-custom.css\")\n");
        sb.append("//   public class YourView extends VerticalLayout { ... }\n");
        sb.append("// ═══════════════════════════════════════════════════════════════════\n\n");

        sb.append("// Method 1: Inject CSS via JavaScript\n");
        sb.append("String customCss = \"\"\"\n");
        // Format CSS for readability, escape text block delimiters
        String css = escapeTextBlock(state.getCustomCss());
        for (String line : css.split("\n")) {
            sb.append("    ").append(line).append("\n");
        }
        sb.append("    \"\"\";\n\n");

        sb.append("editor.getElement().executeJs(\n");
        // 文本块的开始定界符后必须换行
        sb.append("    \"\"\"\n");
        sb.append("    (function(el, css) {\n");
        sb.append("        var style = document.createElement('style');\n");
        sb.append("        style.setAttribute('data-custom-css', 'true');\n");
        sb.append("        style.textContent = css;\n");
        sb.append("        if (el.shadowRoot) {\n");
        sb.append("            el.shadowRoot.appendChild(style);\n");
        sb.append("        } else {\n");
        sb.append("            document.head.appendChild(style);\n");
        sb.append("        }\n");
        sb.append("    })($0, $1)\n");
        sb.append("    \"\"\",\n");
        sb.append("    editor.getElement(),\n");
        sb.append("    customCss\n");
        sb.append(");\n");
    }

    private String quote(String str) {
        return "\"" + escapeJavaString(str) + "\"";
    }

    private String quoteAll(List<String> values) {
        return values.stream().map(v -> quote(v.trim())).collect(Collectors.joining(", "));
    }

    private String stringArray(List<String> values) {
        return "new String[]{" + quoteAll(values) + "}";
    }

    private String escapeJavaString(String str) {
        if (str == null) return "";
        return str.replace("\\", "\\\\")
                  .replace("\"", "\\\"")
                  .replace("\n", "\\n")
                  .replace("\r", "\\r")
                  .replace("\t", "\\t")
                  .replace("\0", "\\0")
                  .replace("\f", "\\f")
                  .replace("\b", "\\b");
    }

    /**
     * 转义 Java 文本块（text block）中的特殊序列
     * 防止用户 CSS 中出现 \""" 终结符导致代码注入
     */
    private String escapeTextBlock(String str) {
        if (str == null) return "";
        return str.replace("\\", "\\\\")
                  .replace("\"\"\"", "\\\"\"\"");
    }

    @Override
    public String getFileExtension() {
        return "java";
    }

    @Override
    public String getDisplayName() {
        return "Java";
    }

    @Override
    public String getMimeType() {
        return "text/x-java-source";
    }
}
